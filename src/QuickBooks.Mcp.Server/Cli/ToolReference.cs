using System.Collections;
using System.Reflection;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;
using Microsoft.Extensions.DependencyInjection;
using ModelContextProtocol.Server;
using QuickBooks.Mcp.Core.Session;
using QuickBooks.Mcp.Server.Writes;

namespace QuickBooks.Mcp.Server.Cli;

/// <summary>Generates docs/TOOLS.md from the registered tools, so the reference cannot drift from the code.</summary>
public static partial class ToolReference
{
    private sealed class NoQuickBooks : IQbClient
    {
        public Task<string> SendAsync(Func<string, string> buildRequest, CancellationToken cancellationToken = default) =>
            throw new InvalidOperationException("The tool reference does not talk to QuickBooks.");
    }

    /// <summary>The tools exactly as a client would see them with everything switched on.</summary>
    public static IReadOnlyList<McpServerTool> AllTools()
    {
        var config = ServerConfig.Load(["--allow-writes", "--allow-payroll"], new Hashtable());
        var services = new ServiceCollection();
        services.AddLogging();
        services.AddSingleton<IQbClient>(new NoQuickBooks());
        services.AddQuickBooksMcp(config);
        using var provider = services.BuildServiceProvider();
        return provider.GetServices<McpServerTool>().OrderBy(CategoryOf, StringComparer.Ordinal).ThenBy(t => t.ProtocolTool.Name, StringComparer.Ordinal).ToList();
    }

    /// <summary>Renders the reference as markdown.</summary>
    public static string Generate()
    {
        var tools = AllTools();
        var sb = new StringBuilder();
        sb.AppendLine("# Tools");
        sb.AppendLine();
        sb.AppendLine("Generated by `quickbooks-mcp --tools-reference` from the registered tools; do not edit by hand (a test fails if it is out of date).");
        sb.AppendLine();
        var reads = tools.Count(t => Kind(t) == "read");
        sb.AppendLine($"**{tools.Count} tools** with everything enabled: {reads} read, {tools.Count(t => Kind(t) == "payroll")} payroll (`--allow-payroll`), {tools.Count - reads - tools.Count(t => Kind(t) == "payroll")} write (`--allow-writes`).");
        sb.AppendLine("By default only the read tools are registered. Every tool accepts only what is listed here; unknown values are refused with a message.");
        sb.AppendLine();

        foreach (var group in tools.GroupBy(CategoryOf))
        {
            sb.AppendLine($"## {group.Key}");
            sb.AppendLine();
            foreach (var tool in group)
            {
                var p = tool.ProtocolTool;
                sb.AppendLine($"### `{p.Name}`");
                sb.AppendLine();
                sb.AppendLine(p.Description);
                sb.AppendLine();
                sb.AppendLine($"Needs: {Needs(tool)}. Example: *\"{ToolExamples.For(p.Name)}\"*");
                sb.AppendLine();
                var schema = p.InputSchema;
                if (schema.TryGetProperty("properties", out var props) && props.EnumerateObject().Any())
                {
                    var required = schema.TryGetProperty("required", out var r) ? r.EnumerateArray().Select(e => e.GetString()).ToHashSet() : [];
                    sb.AppendLine("| Parameter | Type | Description |");
                    sb.AppendLine("|---|---|---|");
                    foreach (var prop in props.EnumerateObject())
                    {
                        var description = prop.Value.TryGetProperty("description", out var d) ? d.GetString() : "";
                        sb.AppendLine($"| `{prop.Name}`{(required.Contains(prop.Name) ? " *" : "")} | {TypeOf(prop.Value)} | {description?.Replace("|", "\\|")} |");
                    }

                    sb.AppendLine();
                    sb.AppendLine("\\* required");
                    sb.AppendLine();
                }
            }
        }

        return sb.ToString().Replace("\r\n", "\n");
    }

    private static string Kind(McpServerTool tool) =>
        tool.ProtocolTool.Name.Contains("payroll", StringComparison.Ordinal) ? "payroll"
        : WriteOps.FromToolName(tool.ProtocolTool.Name) != WriteOp.None || tool.ProtocolTool.Annotations?.ReadOnlyHint == false ? "write"
        : tool.ProtocolTool.Name == "describe_write_fields" ? "write"
        : "read";

    private static string Needs(McpServerTool tool) => Kind(tool) switch
    {
        "payroll" => "`--allow-payroll`",
        "write" => tool.ProtocolTool.Name == "describe_write_fields" ? "any write switch" : $"`{SwitchFor(tool.ProtocolTool.Name)}`",
        _ => "nothing (always available)",
    };

    private static string SwitchFor(string name) => WriteOps.FromToolName(name) switch
    {
        WriteOp.Create => "--allow-writes or QB_ENABLE_WRITE",
        WriteOp.Update => "--allow-writes or QB_ENABLE_UPDATE",
        WriteOp.Delete => "--allow-writes or QB_ENABLE_DELETE",
        _ => "--allow-writes",
    };

    private static string CategoryOf(McpServerTool tool)
    {
        var type = tool.Metadata.OfType<MethodInfo>().FirstOrDefault()?.DeclaringType?.Name ?? "Other";
        return Words().Replace(type.EndsWith("Tools", StringComparison.Ordinal) ? type[..^5] : type, " $1").Trim();
    }

    private static string TypeOf(JsonElement schema)
    {
        var type = schema.TryGetProperty("type", out var t) ? t.ToString() : "any";
        if (t.ValueKind == JsonValueKind.Array) type = string.Join(" or ", t.EnumerateArray().Select(e => e.GetString()).Where(s => s != "null"));
        if (type.Contains("array", StringComparison.Ordinal) && schema.TryGetProperty("items", out var items)) return $"list of {TypeOf(items)}";
        return type.Replace("integer", "number");
    }

    [GeneratedRegex("(?<!^)([A-Z])")]
    private static partial Regex Words();
}
